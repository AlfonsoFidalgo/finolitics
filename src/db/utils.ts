export async function fetchPosts() {
  const posts = await prisma.posts.findMany({
    where: {
      id: {
        in: postsToFetch,
      },
    },
  });

  return posts;
}

(async () => {
  try {
    const res = await fetchPosts();
    console.log("Fetched posts:", res.length);

    const fetchedIds = res.map((post) => post.id);
    const missingIds = postsToFetch.filter((id) => !fetchedIds.includes(id));
    console.log("Missing posts:", missingIds.length);
  } catch (error) {
    console.error("Error in script:", error);
  }
})();
